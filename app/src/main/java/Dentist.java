public class Dentist {

    String name, qualification, phone, email, state;
    int image;

    public Dentist(String name, String qualification, String phone,
                   String email, String state, int image) {
        this.name = name;
        this.qualification = qualification;
        this.phone = phone;
        this.email = email;
        this.state = state;
        this.image = image;
    }
}